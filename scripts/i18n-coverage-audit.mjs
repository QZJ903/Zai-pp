#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const failures = [];
const hanText = /\p{Script=Han}/u;
const scannableExtensions = new Set(['.js', '.jsx', '.json', '.mjs', '.ts', '.tsx']);
const scanTargets = [
  'core',
  'entrypoints',
  'scripts',
  'public/_locales/en',
  'package.json',
  'wxt.config.ts',
];

const pathAllowlist = new Map([
  // z.ai 适配层的三处文件：中文是必需的，不是漏翻译。
  // - `core/zai/*` 与 `entrypoints/zai.content.ts` 含给模型的续跑/纠偏提示词、
  //   z.ai 页面的中文 DOM 选择器（按钮 aria-label、高峰弹窗标题等），
  //   以及工具执行的用户可见摘要。这些既不是 UI chrome（不走 i18n 资源），
  //   也不能翻译（选择器必须与页面逐字匹配）。
  ['core/zai', 'z.ai 适配层：续跑提示词、页面中文 DOM 选择器、工具执行摘要'],
  ['entrypoints/zai.content.ts', 'z.ai 主内容脚本：续跑提示词、页面中文 DOM 选择器、工具执行摘要'],
  ['core/constants.ts', 'Chinese stop words for local Skill matching (source-authored matching data, not UI text)'],
  ['core/i18n/resources/zh-CN', 'zh-CN locale resources (per-section modules; background bundle imports only its section subset)'],
  ['core/mcp/client.ts', 'MCP low-level tool-result diagnostics remain in the protocol layer; localized MCP UI state is covered separately'],
  ['core/mcp/discovery.ts', 'MCP low-level execution diagnostics remain in the protocol layer; localized MCP UI state is covered separately'],
  ['core/skill/builtin.ts', 'canonical built-in Skill source remains zh-CN; English projection is generated by getLocalizedBuiltinSkills'],
  ['core/skill/github-importer.ts', 'GitHub Skill import combines source-authored prompt content and diagnostics; surrounding import UI is locale-backed'],
  ['core/shell/contracts.ts', 'Shell MCP tool metadata mirrors the native-host contract; sidepanel Shell UI is locale-backed'],
  ['scripts/i18n-coverage-audit.mjs', 'audit allowlist contains Chinese fragments that it is designed to detect elsewhere'],
  ['scripts/mcp-live-mock.mjs', 'mock explicitly validates zh-CN continuation prompt behavior'],
  ['scripts/shell-smoke.mjs', 'unicode stdout fixture intentionally verifies non-ASCII shell output'],
  ['scripts/web-search-smoke.mjs', 'legacy smoke fixture intentionally simulates zh-CN web-search prompts and output'],
]);

const lineAllowlist = [
  {
    path: 'core/project/title.ts',
    includes: '探索未至之境',
    reason: 'default GLM conversation title suffix detection',
  },
  {
    path: 'scripts/automation-contract-smoke.mjs',
    includes: "['Agent', '任务']",
    reason: 'negative assertion checks README public-doc leakage fragments',
  },
  {
    path: 'core/skill/local-skill-scorer.ts',
    includes: '适用场景',
    reason: 'scenario-matching regex keywords for applicable scenarios (source-authored matching data, not UI text)',
  },
  {
    path: 'core/skill/local-skill-scorer.ts',
    includes: '不适用场景',
    reason: 'scenario-matching regex keywords for not-applicable scenarios (source-authored matching data, not UI text)',
  },
  {
    path: 'core/skill/local-importer.ts',
    includes: '适用场景',
    reason: 'scenario-matching keywords/labels for applicable scenarios injected into the local-skill index card (source-authored matching data, not UI chrome text)',
  },
  {
    path: 'core/skill/local-importer.ts',
    includes: '不适用场景',
    reason: 'scenario-matching keywords/labels for not-applicable scenarios injected into the local-skill index card (source-authored matching data, not UI chrome text)',
  },
  {
    path: 'core/skill/local-skill-scorer.ts',
    includes: "'财务', '新闻', '报告'",
    reason: 'generic two-character Chinese stop-words used for weak-query down-weighting (source-authored linguistic scoring data, not UI text)',
  },
];

assertDeterministicKeyChecks();
assertAllowlistTargetsExist();

const files = scanTargets.flatMap((target) => collectFiles(resolve(root, target)));
const offenders = [];
const allowed = [];

for (const absolutePath of files) {
  const relativePath = toProjectPath(absolutePath);
  const text = readFileSync(absolutePath, 'utf8');
  if (!hanText.test(text)) continue;

  const pathReason = getPathAllowlistReason(relativePath);
  const lines = text.split(/\r?\n/);
  for (const [index, line] of lines.entries()) {
    if (!hanText.test(line)) continue;
    // Skip comments: this audit exists to catch hardcoded *UI copy*, which lives in
    // string literals and JSX — not in source comments. Chinese comments are the
    // normal authoring language here and are not user-visible.
    const code = stripLineComment(line).trim();
    if (!code) continue;
    if (!hanText.test(code)) continue;
    if (pathReason) {
      allowed.push({ path: relativePath, line: index + 1, reason: pathReason });
      continue;
    }

    const lineReason = getLineAllowlistReason(relativePath, line);
    if (lineReason) {
      allowed.push({ path: relativePath, line: index + 1, reason: lineReason });
      continue;
    }

    offenders.push({
      path: relativePath,
      line: index + 1,
      text: code,
    });
  }
}

/**
 * 去掉一行的注释部分：先处理整行注释（`//`、`*`、`/*` 开头），再处理行尾 `//`
 * 注释（保守处理：不解析字符串字面量里的 `//`，因为 URL 等场景极少伴随中文）。
 */
function stripLineComment(line) {
  const trimmed = line.trim();
  if (trimmed.startsWith('//') || trimmed.startsWith('*') || trimmed.startsWith('/*')) {
    return '';
  }
  const idx = line.indexOf('//');
  return idx >= 0 ? line.slice(0, idx) : line;
}

if (offenders.length > 0) {
  failures.push('Hardcoded Chinese found outside the i18n coverage allowlist:');
  for (const offender of offenders) {
    failures.push(`  ${offender.path}:${offender.line}: ${offender.text}`);
  }
}

if (failures.length > 0) {
  console.error('I18n coverage audit failed:');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

const allowedPaths = new Set(allowed.map((item) => item.path));
console.log(`I18n coverage audit passed (${files.length} files scanned, ${allowedPaths.size} allowlisted paths)`);

function assertDeterministicKeyChecks() {
  const enResource = readText('core/i18n/resources/en.ts');
  const i18nTest = readText('tests/i18n.test.ts');
  if (!enResource.includes('satisfies LocaleMessages')) {
    failures.push('core/i18n/resources/en.ts must keep the compile-time LocaleMessages parity guard');
  }
  if (!i18nTest.includes("keeps English and Chinese string keys in parity")) {
    failures.push('tests/i18n.test.ts must keep string-key parity coverage');
  }
  if (!i18nTest.includes("keeps English and Chinese array keys in parity")) {
    failures.push('tests/i18n.test.ts must keep array-key parity coverage');
  }
}

function assertAllowlistTargetsExist() {
  for (const allowedPath of pathAllowlist.keys()) {
    if (!existsSync(resolve(root, allowedPath))) {
      failures.push(`allowlisted path does not exist: ${allowedPath}`);
    }
  }
  for (const rule of lineAllowlist) {
    const file = readText(rule.path);
    if (!file.includes(rule.includes)) {
      failures.push(`allowlisted line fragment is stale: ${rule.path} :: ${rule.includes}`);
    }
  }
}

function collectFiles(target) {
  const stats = statSync(target);
  if (stats.isFile()) {
    return scannableExtensions.has(extname(target)) ? [target] : [];
  }

  const files = [];
  for (const entry of readdirSync(target)) {
    if (entry === 'node_modules' || entry === '.output' || entry === 'dist') continue;
    const child = join(target, entry);
    const childStats = statSync(child);
    if (childStats.isDirectory()) {
      files.push(...collectFiles(child));
    } else if (scannableExtensions.has(extname(child))) {
      files.push(child);
    }
  }
  return files;
}

function getPathAllowlistReason(relativePath) {
  for (const [allowedPath, reason] of pathAllowlist.entries()) {
    if (relativePath === allowedPath || relativePath.startsWith(`${allowedPath}/`)) return reason;
  }
  return null;
}

function getLineAllowlistReason(relativePath, line) {
  return lineAllowlist.find((rule) => rule.path === relativePath && line.includes(rule.includes))?.reason ?? null;
}

function readText(relativePath) {
  return readFileSync(resolve(root, relativePath), 'utf8');
}

function toProjectPath(absolutePath) {
  // Normalize Windows backslashes so paths match the forward-slash allowlist keys.
  return relative(root, absolutePath).split(/[\\/]/).join('/');
}
